def _grade_mixture_sampler(rng: np.random.Generator, n: int) -> np.ndarray:
    """Draws scores for three separate clusters of students: 20% low scorers
    (mean 22), 50% mid scorers (mean 58), 30% high scorers (mean 88) -- a
    single grade distribution that's secretly three different populations."""
    flags = rng.choice(3, size=n, p=[0.20, 0.50, 0.30])
    vals = np.empty(n, dtype=float)
    for bucket, mu, sigma in [(0, 22.0, 11.0), (1, 58.0, 14.0), (2, 88.0, 8.0)]:
        mask = flags == bucket
        vals[mask] = rng.normal(mu, sigma, size=int(np.sum(mask)))
    return vals


def _group_noise_var(eval_type: str, params, icc: float) -> float:
    """How much extra item-to-item "wobble" (variance) to add on top of a
    "param" shape's base values so the resulting scores have the target
    reliability (icc). Lower icc means more of the spread in observed scores
    is just noise rather than a real difference between items, so this
    returns a bigger number as icc shrinks. Binary scores don't get this
    extra noise layer -- their own pass/fail randomness already is the noise."""
    if eval_type == "continuous":
        a_beta, b_beta = params
        var_base = _beta_var(a_beta, b_beta)
        return var_base * (1.0 / max(icc, 1e-9) - 1.0)
    if eval_type in ("likert", "grades"):
        _mu, total_std = params
        return (1.0 - icc) * total_std ** 2
    raise ValueError(f"_group_noise_var: unsupported eval_type {eval_type!r}")


def group_total_std(shape: ShapeSpec, icc: float) -> float:
    """The overall spread (standard deviation) of one shape's generated
    scores at a given reliability (icc) -- this is the "one unit" that
    Cohen's d effect sizes are measured in everywhere in this harness, so
    "d=0.3" always means "0.3 of this shape's actual spread," not some
    fixed number. Custom shapes use a Monte-Carlo-estimated spread
    (_custom_shape_var) in place of a textbook formula, since they don't
    have one."""
    if shape.kind == "custom":
        return float(np.sqrt(_custom_shape_var(shape) / max(icc, 1e-9)))
    eval_type, params = shape.eval_type, shape.params
    if eval_type == "binary":
        p0 = params
        return float(np.sqrt(p0 * (1.0 - p0)))
    if eval_type == "continuous":
        a_beta, b_beta = params
        return float(np.sqrt(_beta_var(a_beta, b_beta) / max(icc, 1e-9)))
    if eval_type in ("likert", "grades"):
        _mu, total_std = params
        return float(total_std)
    raise ValueError(f"group_total_std: unsupported eval_type {eval_type!r}")


_CUSTOM_SHAPE_VAR_CACHE: dict[str, float] = {}
_CUSTOM_SHAPE_MEAN_CACHE: dict[str, float] = {}
_CUSTOM_SHAPE_RANGE: dict[str, tuple[float, float, bool]] = {
    "binary": (0.0, 1.0, True),
    "continuous": (0.0, 1.0, False), "likert": (1.0, 5.0, True), "grades": (0.0, 100.0, False),
}


def _custom_shape_var(shape: ShapeSpec, *, n_mc: int = 200_000, seed: int = 0) -> float:
    """Estimate a custom shape's variance by drawing a large sample and
    measuring it directly, since there's no textbook formula for a bespoke
    mixture/inflated/heavy-tail sampler. Cached per shape, since the sampler
    always produces the same statistical properties no matter when it's called."""
    if shape.label not in _CUSTOM_SHAPE_VAR_CACHE:
        rng = np.random.default_rng(seed)
        _CUSTOM_SHAPE_VAR_CACHE[shape.label] = float(np.var(shape.custom_sampler(rng, n_mc)))
    return _CUSTOM_SHAPE_VAR_CACHE[shape.label]


def _custom_shape_mean(shape: ShapeSpec, *, n_mc: int = 200_000, seed: int = 1) -> float:
    """Same idea as _custom_shape_var, but for the mean instead of the
    variance: estimate it from a large sample since there's no formula."""
    if shape.label not in _CUSTOM_SHAPE_MEAN_CACHE:
        rng = np.random.default_rng(seed)
        _CUSTOM_SHAPE_MEAN_CACHE[shape.label] = float(np.mean(shape.custom_sampler(rng, n_mc)))
    return _CUSTOM_SHAPE_MEAN_CACHE[shape.label]


_CUSTOM_SHAPE_SORTED_SAMPLE_CACHE: dict[str, np.ndarray] = {}
_CUSTOM_SHAPE_QUANTILE_GRID_CACHE: dict[int, np.ndarray] = {}


def _custom_shape_inverse_cdf(shape: ShapeSpec, q: np.ndarray, *, n_mc: int = 200_000, seed: int = 2) -> np.ndarray:
    """Given percentiles (q, between 0 and 1), return the matching values
    for a custom shape -- e.g. q=0.5 returns roughly the shape's median.

    Well-known distributions like the Beta have a built-in function for
    this ("percent-point function" / inverse CDF). Custom shapes (mixtures,
    inflated distributions, heavy tails) don't, so we approximate it: draw a
    large sample once, sort it, and look up percentiles by linear
    interpolation between the sorted values. This is what lets
    sample_group_truth generate "partially agreeing" groups for custom
    shapes (see its base_corr parameter) the same way it does for
    well-known distributions -- the percentile-lookup step is just
    table-based here instead of formula-based.

    A nice side effect: a "spike" in the data (e.g. 70% of zero-inflated
    values sitting exactly at 0) survives this process exactly, because that
    spike occupies a contiguous block of the sorted sample, so any
    percentile that lands inside it interpolates between two copies of the
    same value.
    """
    if shape.label not in _CUSTOM_SHAPE_SORTED_SAMPLE_CACHE:
        rng = np.random.default_rng(seed)
        _CUSTOM_SHAPE_SORTED_SAMPLE_CACHE[shape.label] = np.sort(shape.custom_sampler(rng, n_mc))
    if n_mc not in _CUSTOM_SHAPE_QUANTILE_GRID_CACHE:
        _CUSTOM_SHAPE_QUANTILE_GRID_CACHE[n_mc] = np.linspace(0.0, 1.0, n_mc)
    sorted_sample = _CUSTOM_SHAPE_SORTED_SAMPLE_CACHE[shape.label]
    grid = _CUSTOM_SHAPE_QUANTILE_GRID_CACHE[n_mc]
    return np.interp(q, grid, sorted_sample)


def _hetero_noise_scale(base: np.ndarray, lo: float, hi: float) -> np.ndarray:
    """Per-item multiplier for "noisier in the middle, quieter at the edges"
    measurement error. Real scores near the boundary of their range (e.g. a
    near-perfect or near-zero score) have less room to wobble than a
    mid-range score does, so this returns close to 0 near lo/hi and peaks
    at 1.0 right in the middle of the range."""
    p = np.clip((base - lo) / (hi - lo), 0.0, 1.0)
    return 2.0 * np.sqrt(p * (1.0 - p))


def _equicorrelated_noise(
    rng: np.random.Generator, n: int, runs: int, k: int, group_vars: np.ndarray, corr: float,
) -> np.ndarray:
    """Generate k streams of random noise (one per group), shape (k, n, runs),
    where every pair of streams has the same correlation `corr` with each
    other, and each stream j has its own variance `group_vars[j]`.

    The trick: draw one "shared" random stream that every group's noise
    partly consists of, plus an "individual" stream unique to each group,
    and blend the two with weights chosen so the resulting correlation
    between any two groups works out to exactly `corr` (corr=0 -> fully
    independent noise per group; corr=1 -> every group sees identical noise).
    """
    shared_z = rng.normal(0.0, 1.0, size=(n, runs))
    out = np.empty((k, n, runs), dtype=float)
    c = max(corr, 0.0)
    for j in range(k):
        std_j = float(np.sqrt(max(group_vars[j], 0.0)))
        indiv_z = rng.normal(0.0, 1.0, size=(n, runs))
        out[j] = std_j * (np.sqrt(c) * shared_z + np.sqrt(max(1.0 - c, 0.0)) * indiv_z)
    return out


def _equicorrelated_std_normal(rng: np.random.Generator, n: int, k: int, base_corr: float) -> np.ndarray:
    """Same shared/individual blending trick as _equicorrelated_noise, but
    for k correlated standard-normal columns (mean 0, variance 1) instead of
    noise with arbitrary per-group variance. Used as the "raw material" for
    generating items that partially (rather than fully) agree across
    groups -- see sample_group_truth's base_corr parameter."""
    shared_z = rng.normal(0.0, 1.0, size=(n, 1))
    bc = max(base_corr, 0.0)
    out = np.empty((k, n, 1), dtype=float)
    for j in range(k):
        indiv_z = rng.normal(0.0, 1.0, size=(n, 1))
        out[j] = np.sqrt(bc) * shared_z + np.sqrt(max(1.0 - bc, 0.0)) * indiv_z
    return out


def sample_group_truth(
    shape: ShapeSpec, n: int, runs: int, k: int, icc: float | Sequence[float], rng: np.random.Generator,
    *, corr: float = 0.5, effects: np.ndarray | None = None,
    heteroscedastic: bool = False, base_corr: float = 1.0,
) -> np.ndarray:
    """Generate scores for one or more groups from a shape in the catalog
    above. This is the single function that every scenario in this file
    eventually calls -- one group for a plain benchmark run, two for an A/B
    comparison, three or more for a multi-model comparison.

    Returns an array of shape (k, n, runs): k groups, n items each, and
    `runs` independent repeats of the whole thing (most callers use runs=1
    and just take the first repeat; runs>1 is for "what if we evaluated the
    same items again with fresh judge noise" scenarios).

    Each item's score is built in two layers:
      1. a "base" value -- the item's real, underlying quality
      2. added noise -- measurement error/judge unreliability layered on top

    icc (intraclass correlation) controls the split between those two
    layers: it's the fraction of the total score variance that comes from
    real differences between items, versus noise. icc=1.0 means no noise at
    all (every observed difference is real); a lower icc means more of what
    you observe is just measurement noise. icc can be one number shared by
    every group, or a list of one number per group if groups should have
    different reliabilities.

    There are two independent ways groups can be related to each other,
    controlled by two separate parameters:

    `corr` -- how correlated the NOISE is across groups. If two groups are
    evaluated under similar conditions (e.g. the same judge having a good or
    bad day), their measurement errors tend to move together rather than
    being independent. corr=0 means each group's noise is drawn completely
    independently; corr=1 means every group gets the exact same noise draw.

    `base_corr` -- how correlated the underlying ITEMS are across groups,
    before any noise is added. The default, base_corr=1.0, means every
    group is scored on the literal same items (e.g. the same prompts judged
    by two different models) -- the common case. A value below 1.0 models
    "different but related" items instead -- e.g. different judges, or
    similar-but-not-identical prompts, where quality tends to be similar
    across groups without being identical.

    To generate base_corr < 1.0, we draw a set of correlated, ordinary
    bell-curve random numbers (one per group, with the desired correlation
    between them), convert each one to a percentile, then look up what
    value that percentile corresponds to in the group's own shape (using
    the shape's own percentile function for "param" shapes, or the
    table-based lookup in _custom_shape_inverse_cdf for "custom" ones). This
    is a standard technique for generating correlated values that follow
    different shapes; statisticians call it a "copula."

    One subtlety worth knowing: base_corr is the correlation of those raw
    bell-curve numbers, not quite the correlation you'll measure in the
    final values -- converting through a shape's percentile function is
    usually not a straight line, so it slightly changes the correlation
    along the way (typically shrinking it somewhat). For shapes with a big
    pile-up of identical values (e.g. 70% of values exactly 0), the
    shrinkage is larger, since identical values don't preserve fine-grained
    rank information. Likert and Grades "param" shapes are an exception:
    their base values are built directly out of the same correlated
    bell-curve numbers with no percentile-function step, so base_corr does
    equal their real correlation almost exactly (aside from a small effect
    from rounding/clamping at the very end).

    A single group (k=1) has no cross-group correlation to speak of -- it
    just gets the full noise variance implied by icc directly. If icc<1.0
    and runs>1, that's the "what if we re-ran this with fresh judge noise"
    multi-run case.

    "custom" shapes (mixtures, inflated distributions, heavy tails, etc.)
    work the same way as "param" shapes here, just using a Monte-Carlo
    estimate of their variance (_custom_shape_var) instead of a textbook
    formula, and the table-based percentile lookup described above instead
    of a built-in one when base_corr < 1.0.
    """
    if effects is None:
        effects = np.zeros(k)
    et = shape.eval_type
    icc_arr = np.full(k, float(icc)) if np.ndim(icc) == 0 else np.asarray(icc, dtype=float)
    if icc_arr.shape != (k,):
        raise ValueError(f"icc must be a scalar or a length-k sequence, got shape {icc_arr.shape} for k={k}")
    icc_scalar = bool(np.ndim(icc) == 0)

    if shape.kind == "custom":
        # "custom" shapes have no closed-form mean/variance/percentile
        # function, so every step below substitutes a Monte-Carlo estimate
        # or table-based lookup (see _custom_shape_var/_custom_shape_inverse_cdf)
        # for what would otherwise be a textbook formula.
        if k == 1:
            base = shape.custom_sampler(rng, n)[:, None]  # (n, 1)
            lo, hi, round_to_int = _CUSTOM_SHAPE_RANGE[et]
            ic = float(icc_arr[0])
            if ic >= 1.0 - 1e-12:
                noise = np.zeros((n, runs))
            else:
                noise_var = _custom_shape_var(shape) * (1.0 / max(ic, 1e-9) - 1.0)
                sigma = float(np.sqrt(max(noise_var, 0.0)))
                if heteroscedastic:
                    noise = rng.normal(0.0, 1.0, size=(n, runs)) * (sigma * _hetero_noise_scale(base, lo, hi))
                else:
                    noise = rng.normal(0.0, sigma, size=(n, runs))
            vals = base + effects[0] + noise
            out = np.empty((1, n, runs), dtype=float)
            out[0] = np.rint(np.clip(vals, lo, hi)) if round_to_int else np.clip(vals, lo, hi)
            return out

        lo, hi, round_to_int = _CUSTOM_SHAPE_RANGE[et]
        if base_corr >= 1.0 - 1e-12:
            # The common case: every group sees the exact same item, so just
            # draw it once and reuse it for all k groups.
            base = np.broadcast_to(shape.custom_sampler(rng, n)[None, :, None], (k, n, 1)).copy()
        else:
            # Partial-agreement case: draw correlated percentiles, then look
            # each one up in this shape's own value table (see
            # _custom_shape_inverse_cdf and sample_group_truth's docstring).
            z = _equicorrelated_std_normal(rng, n, k, base_corr)
            q = np.clip(norm.cdf(z), 1e-9, 1.0 - 1e-9)
            base = _custom_shape_inverse_cdf(shape, q)
        group_noise_vars = np.array([
            _custom_shape_var(shape) * (1.0 / max(ic, 1e-9) - 1.0) if ic < 1.0 - 1e-12 else 0.0
            for ic in icc_arr
        ])
        # base/lo/hi/round_to_int/group_noise_vars are now set, so this
        # continues into the shared noise-injection code below -- the same
        # code path "param" shapes use.

    elif et == "binary":
        base_p = shape.params
        if base_corr >= 1.0 - 1e-12 and icc_scalar:
            # The common case: draw one pass-probability per item, shared by
            # every group, then have each group flip its own biased coin.
            conc = _binary_conc_from_icc(float(icc))
            base = rng.beta(base_p * conc, (1.0 - base_p) * conc, size=(n, 1))
            out = np.empty((k, n, runs), dtype=float)
            for j in range(k):
                p = np.clip(base + effects[j], 0.0, 1.0)
                out[j] = rng.binomial(1, p, size=(n, runs)).astype(float)
            return out
        # Partial agreement, and/or each group having its own reliability:
        # draw correlated percentiles, then look each one up in that group's
        # own Beta-distributed pass-probability curve.
        z = _equicorrelated_std_normal(rng, n, k, base_corr)
        out = np.empty((k, n, runs), dtype=float)
        for j in range(k):
            conc_j = _binary_conc_from_icc(float(icc_arr[j]))
            q_j = np.clip(norm.cdf(z[j]), 1e-9, 1.0 - 1e-9)
            p_j = np.clip(stats.beta.ppf(q_j, base_p * conc_j, (1.0 - base_p) * conc_j) + effects[j], 0.0, 1.0)
            out[j] = rng.binomial(1, p_j, size=(n, runs)).astype(float)
        return out

    elif et == "continuous":
        a_beta, b_beta = shape.params
        lo, hi, round_to_int = 0.0, 1.0, False
        if base_corr >= 1.0 - 1e-12:
            # Common case: one shared Beta-distributed value per item.
            base = np.broadcast_to(rng.beta(a_beta, b_beta, size=(n, 1)), (k, n, 1)).copy()
        else:
            # Partial agreement: correlated percentiles, looked up in this
            # shape's Beta distribution.
            z = _equicorrelated_std_normal(rng, n, k, base_corr)
            q = np.clip(norm.cdf(z), 1e-9, 1.0 - 1e-9)
            base = stats.beta.ppf(q, a_beta, b_beta)
    else:
        # Likert / grades: built directly from a bell-curve ("latent")
        # value, scaled so its spread matches the target reliability (icc),
        # then later rounded/clamped into the visible score range. Because
        # this skips the percentile-function step entirely, base_corr below
        # is also the real correlation between groups' latent values (see
        # sample_group_truth's docstring).
        mu_lat, total_std = shape.params
        lo, hi = (1.0, 5.0) if et == "likert" else (0.0, 100.0)
        round_to_int = et == "likert"
        if base_corr >= 1.0 - 1e-12 and icc_scalar:
            base_std = float(np.sqrt(float(icc))) * total_std
            base = np.broadcast_to(rng.normal(mu_lat, base_std, size=(n, 1)), (k, n, 1)).copy()
        else:
            z = _equicorrelated_std_normal(rng, n, k, base_corr)
            base = mu_lat + total_std * np.sqrt(np.clip(icc_arr, 0.0, 1.0))[:, None, None] * z

    def _finish(vals: np.ndarray) -> np.ndarray:
        """Clamp to the eval type's valid range, and round to a whole number for Likert."""
        return np.rint(np.clip(vals, lo, hi)) if round_to_int else np.clip(vals, lo, hi)

    if shape.kind == "param":
        group_noise_vars = np.array([_group_noise_var(et, shape.params, ic) for ic in icc_arr])
    # ("custom" shapes already computed group_noise_vars above, at k >= 2.)
    out = np.empty((k, n, runs), dtype=float)
    if k == 1:
        if heteroscedastic and group_noise_vars[0] > 0.0:
            scale = _hetero_noise_scale(base[0], lo, hi)
            noise = rng.normal(0.0, 1.0, size=(n, runs)) * (float(np.sqrt(group_noise_vars[0])) * scale)
        else:
            noise = rng.normal(0.0, float(np.sqrt(max(group_noise_vars[0], 0.0))), size=(n, runs))
        out[0] = _finish(base[0] + effects[0] + noise)
        return out

    if heteroscedastic:
        # _equicorrelated_noise assumes a single noise size per group, but
        # heteroscedastic noise needs a different size for every item (see
        # _hetero_noise_scale), so we redo the same shared/individual
        # blending trick by hand here instead. Reusing one shared_z draw
        # across all k groups keeps `corr`'s meaning consistent with the
        # non-heteroscedastic path below.
        shared_z = rng.normal(0.0, 1.0, size=(n, runs))
        c = max(corr, 0.0)
        for j in range(k):
            scale_j = _hetero_noise_scale(base[j], lo, hi)
            indiv_z = rng.normal(0.0, 1.0, size=(n, runs))
            std_j = float(np.sqrt(group_noise_vars[j])) * scale_j
            noise_j = std_j * (np.sqrt(c) * shared_z + np.sqrt(max(1.0 - c, 0.0)) * indiv_z)
            out[j] = _finish(base[j] + effects[j] + noise_j)
        return out

    noise = _equicorrelated_noise(rng, n, runs, k, group_noise_vars, corr)
    for j in range(k):
        out[j] = _finish(base[j] + effects[j] + noise[j])
    return out


def build_single_sample_sources(
    suite: str = "standard", *, run_noise_fracs: list[float] | None = None, heteroscedastic: bool = False,
) -> list[CISource]:
    """Build one CISource per shape in the catalog -- a single-group/single-
    benchmark-run scenario, generated via sample_group_truth(k=1). Used by
    cases/ci_single.py to check whether confidence-interval methods give
    correctly-calibrated intervals around a single benchmark score.

    run_noise_fracs : sequence of float, optional
        If given, switches to "what if we re-ran the same benchmark and got
        fresh judge noise" mode (cases/ci_single.py's ``--nested-mode``):
        for every shape, builds one CISource per run-noise fraction `f` in
        this list, where `f` is the share of total score variance that
        comes from re-run noise rather than real item differences
        (icc = 1 - f). Its ``generate_runs(rng, n, runs) -> (n, runs)``
        field lets a caller draw multiple noisy re-runs of the same n
        items. If ``None`` (the default), every shape just gets one plain,
        single-run CISource.
    heteroscedastic : bool
        Only meaningful when run_noise_fracs is given: makes the size of
        the re-run noise depend on where an item's score falls in its valid
        range (smaller near the boundaries) instead of using one fixed
        noise size for every item -- see sample_group_truth.
    """
    if suite not in SCENARIO_SUITES:
        raise ValueError(f"Unknown scenario suite: {suite}")

    sources: list[CISource] = []
    for eval_type, catalog in SHAPES_BY_EVAL_TYPE.items():
        for shape in _tier_shapes(catalog, suite):
            if run_noise_fracs is None:
                def _gen(rng: np.random.Generator, n: int, _shape: ShapeSpec = shape) -> np.ndarray:
                    return sample_group_truth(_shape, n, 1, 1, 1.0, rng)[0, :, 0]

                true_mean = _estimate_true_mean_mc(_gen)
                sources.append(CISource(label=shape.label, eval_type=eval_type, generate=_gen, true_mean=true_mean))
                continue

            for f in run_noise_fracs:
                icc_ = 1.0 - f

                def _gen_runs(
                    rng: np.random.Generator, n: int, runs: int,
                    _shape: ShapeSpec = shape, _icc: float = icc_,
                ) -> np.ndarray:
                    return sample_group_truth(_shape, n, runs, 1, _icc, rng, heteroscedastic=heteroscedastic)[0]

                true_mean = _estimate_true_mean_mc_runs(_gen_runs)
                sources.append(CISource(
                    label=f"{shape.label}|f={f:.2f}", eval_type=eval_type,
                    generate=lambda rng, n, _g=_gen_runs: _g(rng, n, 1)[:, 0],
                    generate_runs=_gen_runs, true_mean=true_mean, run_noise_frac=f,
                ))

    return sources


# Hand-picked, highly lopsided paired binary (pass/fail) scenarios -- e.g.
# "model A almost always fails where model B succeeds, and they almost never
# disagree the other way." These don't fit the icc/shape catalog above (they
# specify the four joint outcome probabilities directly: both pass, both
# fail, A-only, B-only), but they're useful stress tests for paired tests
# like McNemar's, since real A/B comparisons sometimes really do look this
# lopsided. Each tuple is (label, P(A passes, B fails), P(A fails, B passes),
# P(both pass)) -- shared by build_pair_sources' plain and multi-run paths.
_ASYM_BINARY_SPECS: list[tuple[str, float, float, float]] = [
    ("binary-onesided-neg-extreme", 0.001, 0.384, 0.000),
    ("binary-onesided-pos-extreme", 0.384, 0.001, 0.000),
    ("binary-onesided-neg-strong", 0.020, 0.300, 0.050),
    ("binary-onesided-pos-strong", 0.300, 0.020, 0.050),
    ("binary-onesided-neg-ultra", 0.000, 0.520, 0.000),
    ("binary-onesided-pos-ultra", 0.520, 0.000, 0.000),
    ("binary-onesided-neg-sparse", 0.001, 0.090, 0.030),
    ("binary-onesided-pos-sparse", 0.090, 0.001, 0.030),
    ("binary-onesided-neg-near-ceil", 0.000, 0.080, 0.900),
    ("binary-onesided-pos-near-floor", 0.080, 0.000, 0.020),
    ("binary-onesided-neg-moderate", 0.050, 0.220, 0.150),
    ("binary-onesided-pos-moderate", 0.220, 0.050, 0.150),
]


def _build_pair_sources_multirun(
    suite: str, d_list: list[float], run_noise_fracs: list[float], *,
    heteroscedastic: bool, pairwise_noise_grid: bool, pairwise_noise_grid_max: int | None,
    pairwise_noise_grid_seed: int, cross_item_rho: float,
) -> list[CIPairSource]:
    """The "what if we re-ran both models and got fresh judge noise" version
    of build_pair_sources: same (eval_type, shape, effect size) sweep as the
    plain path, but swept over pairs of run-noise fractions (f_a, f_b)
    instead of fixed reliability values, via
    sample_group_truth(k=2, base_corr=cross_item_rho, icc=[1-f_a, 1-f_b])."""
    if pairwise_noise_grid:
        noise_pairs = [(float(fa), float(fb)) for fa in run_noise_fracs for fb in run_noise_fracs]
    else:
        noise_pairs = [(float(f), float(f)) for f in run_noise_fracs]
    if pairwise_noise_grid_max is not None and pairwise_noise_grid_max > 0 and len(noise_pairs) > pairwise_noise_grid_max:
        rng_grid = np.random.default_rng(pairwise_noise_grid_seed)
        keep_idx = np.sort(rng_grid.choice(len(noise_pairs), size=pairwise_noise_grid_max, replace=False))
        noise_pairs = [noise_pairs[int(i)] for i in keep_idx]

    sources: list[CIPairSource] = []
    for eval_type, catalog in SHAPES_BY_EVAL_TYPE.items():
        shapes_here = _tier_shapes(catalog, suite)
        for f_a, f_b in noise_pairs:
            icc_a, icc_b = 1.0 - f_a, 1.0 - f_b
            icc_eff = 0.5 * (icc_a + icc_b)
            for shape in shapes_here:
                total_std = group_total_std(shape, icc_eff)
                for d in d_list:
                    delta = d * total_std
                    is_null = d == 0.0
                    effect_tag = "null" if is_null else f"d={d:.2f}"
                    label = (
                        f"{shape.label}|fA={f_a:.2f}|fB={f_b:.2f}|{effect_tag}" if pairwise_noise_grid
                        else f"{shape.label}|f={f_a:.2f}|{effect_tag}"
                    )
                    shape_, icc_pair_, delta_ = shape, [icc_a, icc_b], delta

                    def _gen_pair_runs(
                        rng: np.random.Generator, n: int, runs: int,
                        _shape: ShapeSpec = shape_, _icc: list[float] = icc_pair_, _d: float = delta_,
                    ) -> tuple[np.ndarray, np.ndarray]:
                        # corr=0.0: A's and B's re-run noise is independent
                        # here -- only the items themselves are correlated
                        # (via base_corr/cross_item_rho), not the noise on
                        # top of them. This is a separate knob from the
                        # plain (non-multirun) path's corr=0.5 default.
                        out = sample_group_truth(
                            _shape, n, runs, 2, _icc, rng, effects=np.array([0.0, _d]),
                            heteroscedastic=heteroscedastic, base_corr=cross_item_rho, corr=0.0,
                        )
                        return out[0], out[1]

                    true_diff = 0.0 if is_null else _estimate_true_pair_diff(_gen_pair_runs)
                    sources.append(CIPairSource(
                        label=label, eval_type=eval_type, generate_pair=_gen_pair_runs, true_diff=true_diff,
                        icc=icc_eff, cohens_d=d, is_null=is_null,
                        run_noise_frac=0.5 * (f_a + f_b), run_noise_frac_a=f_a, run_noise_frac_b=f_b,
                    ))

    # Re-run version of the lopsided binary stress tests above: each item
    # starts with a fixed joint (A, B) outcome, but on each run there's a
    # probability f_eff that the item's outcome gets redrawn fresh instead
    # of reusing the original one -- the binary analogue of run-noise.
    if suite in ("expanded", "extreme"):
        for shape_label, p10, p01, p11 in _ASYM_BINARY_SPECS:
            p00 = 1.0 - (p11 + p10 + p01)
            if p00 <= 0.0:
                raise ValueError(f"Invalid asymmetric binary scenario {shape_label}: probabilities sum to >= 1.0")
            probs = np.array([p11, p10, p01, p00], dtype=float)
            true_diff = float(p10 - p01)

            for f_a, f_b in noise_pairs:
                f_eff = 0.5 * (f_a + f_b)
                label = (
                    f"{shape_label}|p10={p10:.3f}|p01={p01:.3f}|p11={p11:.3f}|p00={p00:.3f}|fA={f_a:.2f}|fB={f_b:.2f}"
                    if pairwise_noise_grid
                    else f"{shape_label}|p10={p10:.3f}|p01={p01:.3f}|p11={p11:.3f}|p00={p00:.3f}|f={f_eff:.2f}"
                )
                probs_, f_ = probs, f_eff

                def _gen_binary_asym_runs(
                    rng: np.random.Generator, n: int, runs: int, _probs: np.ndarray = probs_, _f: float = f_,
                ) -> tuple[np.ndarray, np.ndarray]:
                    z_item = rng.choice(4, size=(n, 1), p=_probs)
                    z_run = rng.choice(4, size=(n, runs), p=_probs)
                    redraw = rng.random((n, runs)) < _f
                    z = np.where(redraw, z_run, z_item)
                    a = np.isin(z, (0, 1)).astype(float)
                    b = np.isin(z, (0, 2)).astype(float)
                    return a, b

                sources.append(CIPairSource(
                    label=label, eval_type="binary", generate_pair=_gen_binary_asym_runs, true_diff=true_diff,
                    icc=1.0 - f_eff, cohens_d=0.0, is_null=False,
                    run_noise_frac=f_eff, run_noise_frac_a=f_a, run_noise_frac_b=f_b,
                ))

    return sources


def build_pair_sources(
    suite: str = "standard",
    icc_values: list[float] | tuple[float, ...] = (0.10, 0.25, 0.40),
    cohens_d_values: list[float] | tuple[float, ...] = (0.3,),
    include_null: bool = False,
    *,
    run_noise_fracs: list[float] | None = None,
    heteroscedastic: bool = False,
    pairwise_noise_grid: bool = False,
    pairwise_noise_grid_max: int | None = None,
    pairwise_noise_grid_seed: int = 42,
    cross_item_rho: float = 0.7,
) -> list[CIPairSource]:
    """Build paired-comparison scenarios (e.g. "model A vs. model B on the
    same n items") across the whole shape catalog -- including "custom"
    shapes like mixtures and inflated distributions -- by sweeping
    reliability (icc) and effect size (Cohen's d) through
    sample_group_truth(k=2). Used by cases/ci_paired.py to check whether
    paired-difference confidence-interval methods are correctly calibrated.

    The plain path (run_noise_fracs=None) has A and B scored on the literal
    same items (base_corr=1.0, sample_group_truth's default). The multi-run
    path below instead has A and B scored on related-but-not-identical
    items (base_corr=cross_item_rho < 1.0).

    icc = the fraction of total score variance that's real item-to-item
    variation rather than noise (see sample_group_truth). Cohen's d = the
    size of the gap between A and B, measured in units of one shape's own
    spread (group_total_std(shape, icc)) -- so "d=0.3" means the same real
    thing for every shape, not a fixed raw number.

    Parameters
    ----------
    suite : str
        'standard', 'expanded', or 'extreme'.
    icc_values : sequence of float
        Reliability values to sweep. Each value generates a separate scenario batch.
        Ignored when run_noise_fracs is given.
    cohens_d_values : sequence of float
        Non-zero effect sizes to test. A null (d=0) variant is
        automatically prepended when include_null=True.
    include_null : bool
        If True, prepend d=0 scenarios for every (eval_type, shape, icc)
        combination, flagged is_null=True (used to measure Type I error --
        false positives when there's truly no difference).
    run_noise_fracs : sequence of float, optional
        If given, switches to "re-run with fresh judge noise, on
        related-but-not-identical items" mode (cases/ci_paired.py's
        ``--nested-mode``): icc_values is ignored, and instead every (f_a,
        f_b) pair from this list (f_a == f_b unless pairwise_noise_grid) is
        used as A's and B's run-noise fraction, via
        sample_group_truth(k=2, base_corr=cross_item_rho). If ``None`` (the
        default), every scenario is a plain single-run comparison on shared
        items (base_corr=1.0).
    heteroscedastic : bool
        Only meaningful when run_noise_fracs is given -- see sample_group_truth.
    pairwise_noise_grid : bool
        Only meaningful when run_noise_fracs is given: sweep the full (f_a,
        f_b) cross product instead of pairing each f with itself.
    pairwise_noise_grid_max : int, optional
        Only meaningful with pairwise_noise_grid: randomly subsample the
        (f_a, f_b) grid down to this many pairs (deterministic given
        pairwise_noise_grid_seed) if the full grid would be larger.
    cross_item_rho : float
        Only meaningful when run_noise_fracs is given: how correlated A's
        and B's items are with each other (the base_corr fed to
        sample_group_truth) -- 1.0 means identical items, lower values
        model "different but related" items/judges.
    """
    if suite not in SCENARIO_SUITES:
        raise ValueError(f"Unknown scenario suite: {suite}")

    d_list = list(cohens_d_values)
    if include_null:
        d_list = [0.0] + [d for d in d_list if d > 0.0]

    if run_noise_fracs is not None:
        return _build_pair_sources_multirun(
            suite, d_list, run_noise_fracs, heteroscedastic=heteroscedastic,
            pairwise_noise_grid=pairwise_noise_grid, pairwise_noise_grid_max=pairwise_noise_grid_max,
            pairwise_noise_grid_seed=pairwise_noise_grid_seed, cross_item_rho=cross_item_rho,
        )

    sources: list[CIPairSource] = []
    icc_list = list(icc_values)

    for eval_type, catalog in SHAPES_BY_EVAL_TYPE.items():
        shapes_here = _tier_shapes(catalog, suite)
        for icc in icc_list:
            for shape in shapes_here:
                total_std = group_total_std(shape, icc)
                for d in d_list:
                    delta = d * total_std
                    is_null = d == 0.0
                    effect_tag = "null" if is_null else f"d={d:.2f}"
                    label = f"{shape.label}|icc={icc:.2f}|{effect_tag}"
                    shape_, icc_, delta_ = shape, icc, delta

                    def _gen_pair(
                        rng: np.random.Generator, n: int, runs: int,
                        _shape: ShapeSpec = shape_, _icc: float = icc_, _d: float = delta_,
                    ) -> tuple[np.ndarray, np.ndarray]:
                        out = sample_group_truth(_shape, n, runs, 2, _icc, rng, effects=np.array([0.0, _d]))
                        return out[0], out[1]

                    true_diff = 0.0 if is_null else _estimate_true_pair_diff(_gen_pair)
                    sources.append(CIPairSource(
                        label=label, eval_type=eval_type, generate_pair=_gen_pair, true_diff=true_diff,
                        icc=icc, cohens_d=d, is_null=is_null,
                    ))

    # The hand-picked lopsided binary scenarios from _ASYM_BINARY_SPECS above.
    if suite in ("expanded", "extreme"):
        for shape_label, p10, p01, p11 in _ASYM_BINARY_SPECS:
            p00 = 1.0 - (p11 + p10 + p01)
            if p00 <= 0.0:
                raise ValueError(f"Invalid asymmetric binary scenario {shape_label}: probabilities sum to >= 1.0")

            probs = np.array([p11, p10, p01, p00], dtype=float)
            true_diff = float(p10 - p01)
            label = f"{shape_label}|p10={p10:.3f}|p01={p01:.3f}|p11={p11:.3f}|p00={p00:.3f}"

            def _gen_binary_asym(
                rng: np.random.Generator, n: int, runs: int, _probs: np.ndarray = probs,
            ) -> tuple[np.ndarray, np.ndarray]:
                z = rng.choice(4, size=(n, runs), p=_probs)
                a = np.isin(z, (0, 1)).astype(float)
                b = np.isin(z, (0, 2)).astype(float)
                return a, b

            sources.append(CIPairSource(
                label=label, eval_type="binary", generate_pair=_gen_binary_asym, true_diff=true_diff,
                icc=0.0, cohens_d=0.0, is_null=False,
            ))

    return sources


def _estimate_true_mean_mc_runs(
    generate_runs: Callable[[np.random.Generator, int, int], np.ndarray],
    *,
    seed: int = 0,
    n_mc: int = 500_000,
) -> float:
    """Same idea as _estimate_true_mean_mc, for a multi-run generator."""
    rng = np.random.default_rng(seed)
    return float(np.mean(generate_runs(rng, n_mc, 1)))


# ---------------------------------------------------------------------------
# Multi-arm sources (for cases/pvalues.py's multi-arm multiplicity benchmark)
# ---------------------------------------------------------------------------
# Like build_pair_sources, but for comparing k >= 2 arms at once (e.g. five
# models on a leaderboard) instead of just two -- used to check whether
# multiple-comparison corrections keep the false-positive rate under control
# as the number of arms grows. Arm 0 gets the effect-size shift; the rest
# share the same baseline distribution.


def _make_multiarm_true_means_fn(
    generate_scores: Callable[[np.random.Generator, int, int, int, float], np.ndarray],
    alt_delta: float,
) -> Callable[[int, float], np.ndarray]:
    """Build a MultiArmSource.true_means callback for a synthetic k-arm
    generator: arm 0 carries `delta`, arms 1..k-1 stay at the baseline mean
    (see generate_scores' own contract), so only two scalars need estimating
    -- the baseline mean (delta=0.0) and arm 0's shifted mean (delta=alt_delta)
    -- via the same large-sample Monte Carlo technique as
    _estimate_true_pair_diff, since clipping/rounding can shift the realized
    mean away from the raw additive `effects` shift. Computed lazily (only
    when --mode simultaneous_ci actually calls it) and cached, so --mode
    multiarm/pairwise pay no extra cost.
    """
    cache: dict[str, float] = {}

    def _ensure() -> None:
        if cache:
            return
        cache["base"] = float(np.mean(generate_scores(np.random.default_rng(0), 300_000, 1, 1, 0.0)))
        cache["arm0"] = float(np.mean(generate_scores(np.random.default_rng(1), 300_000, 1, 1, alt_delta)))

    def _true_means(k: int, delta: float) -> np.ndarray:
        _ensure()
        out = np.full(k, cache["base"], dtype=float)
        if delta != 0.0:
            out[0] = cache["arm0"]
        return out

    return _true_means


def build_multiarm_sources(
    *, suite: str = "standard", icc: float = 0.20, cohens_d: float = 0.3, eval_types: list[str] | None = None,
) -> list[MultiArmSource]:
    if suite not in SCENARIO_SUITES:
        raise ValueError(f"Unknown scenario suite: {suite}")
    eval_types = list(eval_types) if eval_types is not None else list(EVAL_TYPES)

    def _make_generator(shape: ShapeSpec):
        def _gen(rng: np.random.Generator, n: int, runs: int, k: int, delta: float) -> np.ndarray:
            effects = np.zeros(k)
            effects[0] = delta
            return sample_group_truth(shape, n, runs, k, icc, rng, effects=effects)
        return _gen

    sources: list[MultiArmSource] = []
    for eval_type in eval_types:
        for shape in _tier_shapes(SHAPES_BY_EVAL_TYPE[eval_type], suite):
            generate_scores = _make_generator(shape)
            alt_delta = cohens_d * group_total_std(shape, icc)
            sources.append(MultiArmSource(
                label=shape.label, eval_type=eval_type, generate_scores=generate_scores,
                alt_delta=alt_delta, true_means=_make_multiarm_true_means_fn(generate_scores, alt_delta),
            ))
    return sources


# ---------------------------------------------------------------------------
# Judge-bias sources (for cases/pvalues.py's PPI-correction calibration mode)
# ---------------------------------------------------------------------------
# This section models an LLM-as-judge setup: ground-truth scores exist, but
# we only see (a) a biased/noisy LLM-judge score for every item, and (b) a
# small number of accurate human labels. The question PPI (prediction-powered
# inference) correction answers is whether we can still test hypotheses
# correctly using mostly-LLM-judged data plus a few real labels -- this
# section sweeps one judge-bias/noise/labeling factor at a time, on top of
# the same per-eval-type truth model the rest of the file uses, to check
# whether that correction holds up. `eval_type="binary"` is supported only
# for the two-independent-groups mean-based tests (ttest/ttest_welch/
# paired_t -- a proportion is just the mean of a 0/1 variable, so PPI's
# rectifier applies exactly as it does for continuous data); the rank-based
# family (mw/wilcoxon/friedman/kruskal) and ANOVA/LMM are NOT extended to
# binary here (heavily-tied 0/1 data breaks rank tests, and the additive
# noise/bias/slope judge model below doesn't apply to a 0/1 judgment either
# -- see _jb_llm_binary/_jb_llm_repeated_binary for the confusion-matrix
# model used instead), so those tests are skipped for binary scenarios (see
# cases/pvalues.py's _ppi_effective_tests).

_PPI_REPRESENTATIVE_SHAPE_LABEL: dict[str, str] = {
    "continuous": "cont-right-skew", "likert": "likert-mid", "grades": "grades-mid",
    "binary": "p=0.50",
}


def _ppi_shape(eval_type: str, shape_label: str | None = None) -> ShapeSpec:
    """Look up the ShapeSpec a judge-bias scenario should draw truth from --
    a specific override (shape_label) if given, otherwise the eval type's
    default representative shape (_PPI_REPRESENTATIVE_SHAPE_LABEL)."""
    label = shape_label if shape_label is not None else _PPI_REPRESENTATIVE_SHAPE_LABEL[eval_type]
    return next(s for s in SHAPES_BY_EVAL_TYPE[eval_type] if s.label == label)


def _ppi_shape_anchor(shape: ShapeSpec) -> float:
    """The mean of a shape's truth distribution. Used as the reference
    point the judge-bias/slope model below distorts scores around -- e.g. a
    judge that "compresses" scores toward the middle does so relative to
    this point, not relative to 0."""
    if shape.kind == "custom":
        return _custom_shape_mean(shape)
    if shape.eval_type == "continuous":
        a, b = shape.params
        return a / (a + b)
    if shape.eval_type == "binary":
        return float(shape.params)  # binary: params is the bare pass rate
    return float(shape.params[0])  # likert/grades: (mean, total spread)


_JB_MIN_LAB = 15  # always label at least this many items, even if label_frac would round down further
JUDGE_BIAS_LMM_RUNS_R = 3  # number of repeated LLM "re-runs" simulated for the nested-runs test structure
JUDGE_BIAS_LMM_FACTORIAL_FACTORS = pd.DataFrame({
    "f1": ["a", "a", "b", "b"],
    "f2": ["x", "y", "x", "y"],
})


def _jb_biases(scenario: JudgeBiasSource) -> tuple[float, float, float]:
    """The (group A, group B, group C) judge bias amounts for a 3-group
    scenario. "none" = no bias; "constant" = every group gets the same
    bias (so a paired/relative test should still come out unbiased);
    "differential" = only group A is biased, which a paired/relative test
    SHOULD be able to detect as a real difference."""
    if scenario.bias_type == "none":
        return 0.0, 0.0, 0.0
    if scenario.bias_type == "constant":
        return scenario.bias_const, scenario.bias_const, scenario.bias_const
    if scenario.bias_type == "differential":
        return scenario.bias_delta, 0.0, 0.0
    raise ValueError(f"Unknown bias_type: {scenario.bias_type!r}")


def _jb_biases_4(scenario: JudgeBiasSource) -> tuple[float, float, float, float]:
    """Same as _jb_biases, for the 4-group (2x2 factorial) test structure."""
    if scenario.bias_type == "none":
        return 0.0, 0.0, 0.0, 0.0
    if scenario.bias_type == "constant":
        return (scenario.bias_const,) * 4
    if scenario.bias_type == "differential":
        return scenario.bias_delta, 0.0, 0.0, 0.0
    raise ValueError(f"Unknown bias_type: {scenario.bias_type!r}")


def _jb_judge_params_3(scenario: JudgeBiasSource) -> tuple[tuple[float, float, float], tuple[float, float, float]]:
    """The full per-group judge-miscalibration parameters for 3 groups:
    each group's bias (its overall offset from the truth) and slope (how
    much it stretches or compresses the score range)."""
    b1, b2, b3 = _jb_biases(scenario)
    biases = (b1 + scenario.bias_extra_a, b2 + scenario.bias_extra_b, b3 + scenario.bias_extra_c)
    slopes = (scenario.slope_a, scenario.slope_b, scenario.slope_c)
    return biases, slopes


def _jb_judge_params_4(
    scenario: JudgeBiasSource,
) -> tuple[tuple[float, float, float, float], tuple[float, float, float, float]]:
    """Same as _jb_judge_params_3, for the 4-group (2x2 factorial) test structure."""
    b1, b2, b3, b4 = _jb_biases_4(scenario)
    biases = (b1 + scenario.bias_extra_a, b2 + scenario.bias_extra_b, b3 + scenario.bias_extra_c, b4 + scenario.bias_extra_d)
    slopes = (scenario.slope_a, scenario.slope_b, scenario.slope_c, scenario.slope_d)
    return biases, slopes


def _contaminated_noise_stds(noise_sd: float, contam_frac: float, contam_scale: float) -> tuple[float, float]:
    """Work out the two noise sizes for a "judge is usually right, but
    sometimes way off" error model: a normal-width error most of the time,
    and a much wider (contam_scale times bigger) "catastrophic" error the
    rest of the time (with probability contam_frac). The two widths are
    solved so that, blended together, their overall noise size still comes
    out to exactly noise_sd -- so swapping in this noise model doesn't
    change what noise_sd means anywhere else in the harness, only how that
    fixed amount of noise is distributed across items.
    """
    noise_var = noise_sd ** 2
    denom = (1.0 - contam_frac) + contam_frac * contam_scale ** 2
    sigma_normal = float(np.sqrt(noise_var / max(denom, 1e-12)))
    sigma_catastrophic = contam_scale * sigma_normal
    return sigma_normal, sigma_catastrophic


def _jb_llm(
    truth: np.ndarray, bias: float, noise_sd: float, rng: np.random.Generator,
    slope: float = 1.0, anchor: float = 0.0,
    noise_family: str = "gaussian", contam_frac: float = 0.10, contam_scale: float = 4.0,
) -> np.ndarray:
    """Turn ground-truth scores into simulated LLM-judge scores: apply a
    miscalibration (`slope` stretches/compresses the range around `anchor`,
    `bias` shifts it), then add measurement-error noise. `noise_family`
    picks how that noise is distributed -- "gaussian" (plain, symmetric
    noise) or "contaminated" (see _contaminated_noise_stds)."""
    pred = anchor + slope * (truth - anchor) + bias
    if noise_sd == 0.0:
        return pred
    if noise_family == "gaussian":
        return pred + rng.normal(0.0, noise_sd, len(truth))
    if noise_family == "contaminated":
        sigma_normal, sigma_catastrophic = _contaminated_noise_stds(noise_sd, contam_frac, contam_scale)
        is_catastrophic = rng.random(len(truth)) < contam_frac
        sd_per_item = np.where(is_catastrophic, sigma_catastrophic, sigma_normal)
        return pred + rng.normal(0.0, 1.0, len(truth)) * sd_per_item
    raise ValueError(f"Unknown noise_family: {noise_family!r}")


def _jb_llm_repeated(
    truths: list[np.ndarray], biases: list[float], noise_sds: list[float], slopes: list[float],
    rng: np.random.Generator, anchor: float, corr: float,
    noise_family: str = "gaussian", contam_frac: float = 0.10, contam_scale: float = 4.0,
) -> list[np.ndarray]:
    """Same idea as _jb_llm, but for several groups/conditions at once,
    where their judge errors should be correlated rather than independent
    (`corr`) -- e.g. the same judge scoring the same item under several
    conditions, where a bad day affects every condition's score together."""
    if len(truths) == 0:
        return []
    n = len(truths[0])
    if corr <= 0.0:
        return [
            _jb_llm(tr, b, s, rng, slope=m, anchor=anchor, noise_family=noise_family,
                    contam_frac=contam_frac, contam_scale=contam_scale)
            for tr, b, s, m in zip(truths, biases, noise_sds, slopes)
        ]

    corr_clamped = min(max(corr, 0.0), 0.999)
    w_shared = float(np.sqrt(corr_clamped))
    w_ind = float(np.sqrt(1.0 - corr_clamped))

    if noise_family == "gaussian":
        shared = rng.normal(0.0, 1.0, n)
        out: list[np.ndarray] = []
        for tr, b, sd, m in zip(truths, biases, noise_sds, slopes):
            pred = anchor + m * (tr - anchor) + b
            if sd == 0.0:
                out.append(pred)
                continue
            err = sd * (w_shared * shared + w_ind * rng.normal(0.0, 1.0, n))
            out.append(pred + err)
        return out

    if noise_family == "contaminated":
        # shared_regime decides, per item, whether THIS item is having a
        # "catastrophic error" moment -- and that decision is itself
        # correlated across groups/conditions by `corr` (same shared/
        # individual blending idea as _equicorrelated_std_normal, just
        # thresholded into a yes/no event instead of used as a number
        # directly). This represents "the judge has a bad day on this
        # specific item" as something that tends to affect every condition
        # together, not independently. The size of the error within
        # whichever regime an item lands in is still drawn independently
        # per group/condition.
        shared_regime = rng.normal(0.0, 1.0, n)
        out = []
        for tr, b, sd, m in zip(truths, biases, noise_sds, slopes):
            pred = anchor + m * (tr - anchor) + b
            if sd == 0.0:
                out.append(pred)
                continue
            sigma_normal, sigma_catastrophic = _contaminated_noise_stds(sd, contam_frac, contam_scale)
            u = w_shared * shared_regime + w_ind * rng.normal(0.0, 1.0, n)
            is_catastrophic = norm.cdf(u) < contam_frac
            sd_per_item = np.where(is_catastrophic, sigma_catastrophic, sigma_normal)
            err = rng.normal(0.0, 1.0, n) * sd_per_item
            out.append(pred + err)
        return out

    raise ValueError(f"Unknown noise_family: {noise_family!r}")


def _jb_llm_binary(truth: np.ndarray, bias: float, noise_level: float, rng: np.random.Generator) -> np.ndarray:
    """Binary analogue of _jb_llm: turn a 0/1 ground-truth array into a 0/1
    "LLM judge" array via a confusion-matrix (flip-probability) model,
    rather than additive noise -- adding continuous noise to a 0/1 value
    wouldn't stay in {0, 1}.

    `noise_level` is the SYMMETRIC base misclassification rate (same
    numeric range/meaning as the continuous scenarios' llm_noise): with
    bias=0, the judge flips a true 1 to 0 (and a true 0 to 1) with that
    same probability either way. `bias` then pulls those two error rates
    apart in opposite directions -- positive bias makes the judge more
    likely to report 1 regardless of the truth (lower false-negative rate,
    higher false-positive rate), mirroring how a positive `bias` shifts
    predicted scores upward in the continuous model. `slope` and
    `noise_family` have no analogue here (not yet meaningful for a plain
    flip-probability judge) and are simply not modeled.
    """
    flip_neg = float(np.clip(noise_level - bias / 2.0, 0.0, 1.0))  # P(judge=0 | truth=1)
    flip_pos = float(np.clip(noise_level + bias / 2.0, 0.0, 1.0))  # P(judge=1 | truth=0)
    u = rng.random(len(truth))
    is_pos = truth >= 0.5
    return np.where(is_pos, (u >= flip_neg).astype(float), (u < flip_pos).astype(float))


def _jb_llm_repeated_binary(
    truths: list[np.ndarray], biases: list[float], noise_levels: list[float],
    rng: np.random.Generator, corr: float,
) -> list[np.ndarray]:
    """Binary analogue of _jb_llm_repeated: correlated confusion-matrix
    judge decisions across several paired/repeated conditions, via a
    shared latent Gaussian (thresholded per item against each condition's
    own flip probabilities) instead of shared additive noise -- the same
    shared/individual blending idea _jb_llm_repeated uses, just with a
    threshold instead of an addition as the last step."""
    if len(truths) == 0:
        return []
    n = len(truths[0])
    corr_clamped = min(max(corr, 0.0), 0.999)
    w_shared = float(np.sqrt(corr_clamped))
    w_ind = float(np.sqrt(1.0 - corr_clamped))
    shared = rng.normal(0.0, 1.0, n)

    out: list[np.ndarray] = []
    for truth, bias, noise_level in zip(truths, biases, noise_levels):
        flip_neg = float(np.clip(noise_level - bias / 2.0, 0.0, 1.0))
        flip_pos = float(np.clip(noise_level + bias / 2.0, 0.0, 1.0))
        z = w_shared * shared + w_ind * rng.normal(0.0, 1.0, n)
        u = norm.cdf(z)
        is_pos = truth >= 0.5
        out.append(np.where(is_pos, (u >= flip_neg).astype(float), (u < flip_pos).astype(float)))
    return out


def _jb_label_indices(
    signal: np.ndarray, n_lab: int, rng: np.random.Generator,
    mnar: bool, mnar_strength: float, mnar_mode: str,
) -> np.ndarray:
    """Pick which n_lab out of len(signal) items get a real human label.

    If mnar is False, picks uniformly at random -- labeling effort is
    "missing completely at random." If mnar is True ("missing not at
    random"), items get picked with probability weighted by `signal`
    instead, modeling a more realistic labeling process where humans are
    more likely to double-check certain items rather than a random subset:
    mnar_mode="high" preferentially labels high-scoring items;
    "extreme" preferentially labels items with unusually high OR low
    scores. mnar_strength controls how strong that preference is (0 =
    uniform, larger = more skewed toward the preferred items).
    """
    n = len(signal)
    if (not mnar) or mnar_strength <= 0.0:
        return rng.choice(n, n_lab, replace=False)

    scale = float(np.std(signal, ddof=0))
    if scale <= 1e-12:
        return rng.choice(n, n_lab, replace=False)
    z = (signal - float(np.mean(signal))) / scale
    if mnar_mode == "high":
        score = z
    elif mnar_mode == "extreme":
        score = np.abs(z)
    else:
        raise ValueError(f"Unknown mnar_mode: {mnar_mode!r}")

    logits = mnar_strength * score
    logits = logits - float(np.max(logits))
    weights = np.exp(logits)
    probs = weights / float(np.sum(weights))
    return rng.choice(n, n_lab, replace=False, p=probs)


def _jb_labels_independent(
    truth: np.ndarray, frac: float, rng: np.random.Generator,
    mnar: bool = False, mnar_strength: float = 1.0, mnar_mode: str = "high",
) -> np.ndarray:
    """Reveal the true score for a `frac` fraction of one group's items
    (chosen via _jb_label_indices) and hide the rest as NaN -- simulating
    "we only have human labels for some of the items the LLM judged."""
    n = len(truth)
    if n < _JB_MIN_LAB:
        raise ValueError(f"Need n >= {_JB_MIN_LAB} to enforce n_lab >= {_JB_MIN_LAB}; got n={n}")
    n_lab = min(n, max(_JB_MIN_LAB, int(round(n * frac))))
    lab = np.full(n, np.nan)
    idx = _jb_label_indices(truth, n_lab, rng, mnar, mnar_strength, mnar_mode)
    lab[idx] = truth[idx]
    return lab


def _jb_labels_shared(
    truths: list[np.ndarray], frac: float, rng: np.random.Generator,
    mnar: bool = False, mnar_strength: float = 1.0, mnar_mode: str = "high",
) -> list[np.ndarray]:
    """Same idea as _jb_labels_independent, but for several
    paired/repeated groups at once: the SAME set of items gets labeled
    across every group (e.g. the same n prompts get human-labeled for both
    model A's and model B's responses), chosen based on each item's average
    truth across groups rather than any single group's truth alone."""
    n = len(truths[0])
    if n < _JB_MIN_LAB:
        raise ValueError(f"Need n >= {_JB_MIN_LAB} to enforce n_lab >= {_JB_MIN_LAB}; got n={n}")
    n_lab = min(n, max(_JB_MIN_LAB, int(round(n * frac))))
    signal = np.mean(np.column_stack(truths), axis=1)
    idx = _jb_label_indices(signal, n_lab, rng, mnar, mnar_strength, mnar_mode)
    labs = []
    for truth in truths:
        lab = np.full(n, np.nan)
        lab[idx] = truth[idx]
        labs.append(lab)
    return labs


def _jb_bias_magnitude(eval_type: str, frac: float = 0.30) -> float:
    """`frac` of `eval_type`'s own EVAL_TYPE_SCALE_BOUNDS span, as an
    absolute bias_delta value.

    `bias_delta`/`bias_const` are RAW additive offsets on the eval type's
    own native scale (see _jb_llm: ``pred = anchor + slope*(truth-anchor)
    + bias``), NOT normalized to a common [0, 1] fraction -- so reusing the
    same absolute number (e.g. the historical default of 0.30) across eval
    types gives wildly different real severities: "30% of range" for
    continuous ([0, 1]) but only "0.3% of range" for grades ([0, 100]).
    Confirmed empirically that reusing 0.30 verbatim made grades' bias
    scenarios produce essentially NO Type-I inflation (~5%, indistinguishable
    from no bias at all) while continuous saturated at 100% -- not a
    deliberate difference in severity, just an unconverted unit. Binary is
    not meant to be passed here: its bias model (_jb_llm_binary) works via
    flip-probabilities, not an additive offset, so this fractional framing
    doesn't apply to it (its EVAL_TYPE_SCALE_BOUNDS span of 1.0 happens to
    match continuous's anyway, so its historical bias_delta=0.30 was
    already correctly scaled by coincidence).
    """
    lo, hi = EVAL_TYPE_SCALE_BOUNDS[eval_type]
    return frac * (hi - lo)


def _jb_effect_magnitude(eval_type: str, frac: float) -> float:
    """`frac` of `eval_type`'s own EVAL_TYPE_SCALE_BOUNDS span, as an
    absolute JudgeBiasSource.effect_size value -- the same eval-type-relative
    fractional convention _jb_bias_magnitude uses for bias_delta, so
    "how big a real effect" and "how big a judge bias" are expressed on a
    directly comparable scale. Binary is excluded for the same reason
    build_ppi_power_sources doesn't sweep it: generate_judge_bias_cell adds
    effect_size directly onto a 0/1 truth draw (``truth_b2 = _marginal(n2) +
    es``), which only stays valid at es=0 -- any nonzero shift would push
    binary truth values outside {0, 1}."""
    lo, hi = EVAL_TYPE_SCALE_BOUNDS[eval_type]
    return frac * (hi - lo)


def build_judge_bias_sources() -> list[JudgeBiasSource]:
    """A curated, one-factor-at-a-time sweep of judge-bias scenarios. Every
    scenario starts from the same baseline (B, below) and changes exactly
    one thing -- eval type, sample size, group balance, label fraction,
    how labels get chosen, LLM noise level, bias type, scale/slope
    miscalibration, per-group miscalibration, repeated-measures error
    correlation, heteroskedastic noise, or noise family -- plus a few
    scenarios at the end that change several factors together as a
    harder stress test."""
    B: dict = dict(
        eval_type="continuous", icc=0.20, n=100, n2=None, n3=None,
        label_frac=0.20, llm_noise=0.20, llm_noise2=None, llm_noise3=None,
        bias_type="differential", bias_delta=0.30, bias_const=0.40,
        bias_extra_a=0.0, bias_extra_b=0.0, bias_extra_c=0.0, bias_extra_d=0.0,
        slope_a=1.0, slope_b=1.0, slope_c=1.0, slope_d=1.0,
        label_mnar=False, mnar_strength=1.0, mnar_mode="high",
        repeated_corr=0.0,
    )

    S: list[JudgeBiasSource] = []

    def make_scenario(name, tag, **kw):
        return JudgeBiasSource(name=name, tag=tag, **{**B, **kw})

    for eval_type in ["continuous", "likert", "grades"]:
        S.append(make_scenario(
            f"eval_type.{eval_type}", "eval_type", eval_type=eval_type,
            bias_delta=_jb_bias_magnitude(eval_type),
        ))

    # Binary is a separate, smaller-scope scenario (not swept across every
    # other factor below the way continuous/likert/grades are): only the
    # mean-based tests (ttest/ttest_welch/paired_t) apply to it -- see the
    # module-level comment above _PPI_REPRESENTATIVE_SHAPE_LABEL -- so this
    # single baseline-settings scenario is the starting point for validating
    # PPI correction on binary (proportion) judge data.
    S.append(make_scenario("eval_type.binary", "eval_type", eval_type="binary"))

    # Truth-distribution shape factor: does PPI correction still fix Type-I
    # inflation when the underlying truth is a pathological ("custom")
    # shape -- refusal-like zero-inflation, bimodal pass/fail, multi-modal
    # scoring clusters -- instead of the smooth Beta/Normal representative
    # shape every other scenario in this sweep uses? See ShapeSpec/
    # _ppi_shape/JudgeBiasSource.shape_label.
    S.append(make_scenario("shape.cont-zero-inflated", "shape", eval_type="continuous", shape_label="cont-zero-inflated"))
    S.append(make_scenario(
        "shape.likert-bimodal", "shape", eval_type="likert", shape_label="likert-bimodal",
        bias_delta=_jb_bias_magnitude("likert"),
    ))
    S.append(make_scenario(
        "shape.grades-mixture", "shape", eval_type="grades", shape_label="grades-mixture",
        bias_delta=_jb_bias_magnitude("grades"),
    ))

    for n in [60, 100, 200, 400]:
        S.append(make_scenario(f"n={n}", "sample_size", n=n))

    S.append(make_scenario("balance.1:1", "balance", n=100, n2=100, n3=100))
    S.append(make_scenario("balance.2:1", "balance", n=67, n2=133, n3=100))
    S.append(make_scenario("balance.4:1", "balance", n=40, n2=160, n3=100))

    for lab in [0.05, 0.10, 0.20, 0.40]:
        S.append(make_scenario(f"lab.{lab:.0%}", "label_frac", label_frac=lab))

    S.append(make_scenario("label.mcar", "label_mechanism", label_mnar=False, mnar_strength=0.0))
    S.append(make_scenario("label.mnar-mild", "label_mechanism", label_mnar=True, mnar_strength=0.8, mnar_mode="high"))
    S.append(make_scenario("label.mnar-strong", "label_mechanism", label_mnar=True, mnar_strength=1.6, mnar_mode="high"))

    for noise in [0.0, 0.10, 0.35, 0.70]:
        S.append(make_scenario(f"noise.{noise}", "llm_noise", llm_noise=noise))

    for bt in ["none", "constant", "differential"]:
        S.append(make_scenario(f"bias.{bt}", "bias_type", bias_type=bt))

    # Bias MAGNITUDE gradient (differential only -- that's the type a
    # relative/paired test should be able to detect; "constant" bias is
    # deliberately the same for every group regardless of magnitude, so it
    # doesn't need one -- see _jb_biases). The trio above only contrasts
    # bias ABSENT (bias.none) against bias PRESENT at the shared baseline's
    # fixed bias_delta=0.30, which is large enough that nearly every
    # differential-biased scenario in this catalog saturates near a 100%
    # uncorrected rejection rate -- with no scenario anywhere showing a
    # smaller, more realistic judge-bias magnitude, the Type-I calibration
    # plot's uncorrected dots cluster at the two extremes (~alpha or ~1.0)
    # with nothing in between, which can look artificially bimodal/extreme
    # to a reader skimming the plot.
    #
    # `bias_delta`/`bias_const` are RAW additive offsets on each eval type's
    # own native scale (see _jb_llm: `pred = anchor + slope*(truth-anchor) +
    # bias`), NOT normalized to a common [0, 1] fraction -- see
    # _jb_bias_magnitude's docstring for why every differential-bias
    # scenario above (eval_type.*/shape.*) uses it instead of a bare
    # number. This sweep expresses magnitude as a FRACTION of each eval
    # type's own EVAL_TYPE_SCALE_BOUNDS span, so "mild"/"moderate"/"severe"
    # mean the same relative severity everywhere. Verified empirically
    # (n=100/icc=0.20, uncorrected ttest rejection rate, alpha=0.05): 3% of
    # span -> ~12-24%, 7% -> ~45-74%, 30% -> 100%, consistently across
    # continuous/likert/grades. Binary is excluded -- its bias model
    # (_jb_llm_binary) works via flip-probabilities, not an additive offset
    # on a continuous scale, so this fractional framing doesn't apply the
    # same way (though its span happens to match continuous's anyway).
    for et in ["continuous", "likert", "grades"]:
        for label, frac in [("mild", 0.03), ("moderate", 0.07), ("severe", 0.30)]:
            S.append(make_scenario(
                f"biasmag.{et}.{label}", "bias_magnitude",
                eval_type=et, bias_type="differential", bias_delta=_jb_bias_magnitude(et, frac),
            ))

    S.append(make_scenario(
        "scale.none", "scale_bias", bias_type="none", slope_a=1.0, slope_b=1.0, slope_c=1.0, slope_d=1.0,
    ))
    S.append(make_scenario(
        "scale.compress", "scale_bias", bias_type="none", slope_a=0.80, slope_b=0.80, slope_c=0.80, slope_d=0.80,
    ))
    S.append(make_scenario(
        "scale.expand", "scale_bias", bias_type="none", slope_a=1.20, slope_b=1.20, slope_c=1.20, slope_d=1.20,
    ))

    # Per-group differential bias+slope miscalibration ("strong" below is
    # the base pattern -- group a over-scored/expanded, b under-scored/
    # compressed, c mildly over, d moderately under -- everything else is
    # that SAME pattern scaled by a fraction f). The historical "mild"
    # (f=0.5 of "strong") already saturates to ~100% uncorrected rejection,
    # identically to "strong" itself -- not actually milder in practice, the
    # same magnitude-labeling problem build_judge_bias_sources' bias_magnitude
    # sweep found and fixed for bias_delta. Verified empirically (n=100,
    # icc=0.20, uncorrected anova_ind rejection rate, alpha=0.05): f=0.05 ->
    # ~6%, f=0.10 -> ~21%, f=0.20 -> ~58%, f=0.30 -> ~91%, f=0.40+ -> ~100%
    # (saturated) -- so f=0.05/0.10/0.20 are the fractions that actually
    # land in between "none" (f=0) and "strong" (f=1, kept at its original
    # values since it's already a validated saturated-severity reference).
    def _gcal_kwargs(frac: float) -> dict:
        pattern = {"a": 0.30, "b": -0.10, "c": 0.10, "d": -0.20}
        kwargs: dict = {}
        for g, v in pattern.items():
            kwargs[f"bias_extra_{g}"] = v * frac
            kwargs[f"slope_{g}"] = 1.0 + v * frac
        return kwargs

    S.append(make_scenario("gcal.none", "group_calibration", bias_type="none"))
    S.append(make_scenario("gcal.very-mild", "group_calibration", bias_type="none", **_gcal_kwargs(0.05)))
    S.append(make_scenario("gcal.mild", "group_calibration", bias_type="none", **_gcal_kwargs(0.10)))
    S.append(make_scenario("gcal.moderate", "group_calibration", bias_type="none", **_gcal_kwargs(0.20)))
    S.append(make_scenario(
        "gcal.strong", "group_calibration", bias_type="none",
        bias_extra_a=0.30, bias_extra_b=-0.10, bias_extra_c=0.10, bias_extra_d=-0.20,
        slope_a=1.30, slope_b=0.90, slope_c=1.10, slope_d=0.80,
    ))

    S.append(make_scenario("corr.0.0", "repeated_corr", repeated_corr=0.0, bias_type="none"))
    S.append(make_scenario("corr.0.3", "repeated_corr", repeated_corr=0.3, bias_type="none"))
    S.append(make_scenario("corr.0.7", "repeated_corr", repeated_corr=0.7, bias_type="none"))

    S.append(make_scenario("hetero.mild", "heteroskedastic", llm_noise=0.05, llm_noise2=0.50, llm_noise3=0.25))
    S.append(make_scenario("hetero.extreme", "heteroskedastic", llm_noise=0.02, llm_noise2=0.80, llm_noise3=0.40))

    # Judge-noise FAMILY factor: does PPI correction still fix Type-I
    # inflation when judge measurement error is "mostly right, occasionally
    # way off" (see _contaminated_noise_stds) instead of plain, symmetric
    # Gaussian noise? See JudgeBiasSource.noise_family for what this changes
    # (and doesn't: the total noise variance stays the same either way).
    S.append(make_scenario(
        "noise_family.contaminated-mild", "noise_family",
        noise_family="contaminated", contam_frac=0.10, contam_scale=3.0,
    ))
    S.append(make_scenario(
        "noise_family.contaminated-strong", "noise_family",
        noise_family="contaminated", contam_frac=0.10, contam_scale=6.0,
    ))
    S.append(make_scenario(
        "noise_family.contaminated+corr", "noise_family",
        noise_family="contaminated", contam_frac=0.15, contam_scale=5.0, repeated_corr=0.5,
    ))

    S.append(make_scenario("stress.small+sparse", "stress", n=30, label_frac=0.07))
    S.append(make_scenario("stress.large+noisy", "stress", n=300, llm_noise=0.70))
    S.append(make_scenario("stress.unbal+diff", "stress", n=40, n2=200, label_frac=0.08))
    S.append(make_scenario("stress.tiny_lab", "stress", n=200, label_frac=0.02))

    S.append(make_scenario(
        "interact.small+unbal+hetero+diff", "interaction",
        n=30, n2=120, n3=80, label_frac=0.05, llm_noise=0.05, llm_noise2=0.70, llm_noise3=0.35,
        bias_type="differential",
    ))
    S.append(make_scenario(
        "interact.small+sparse+noisy+const", "interaction",
        n=40, label_frac=0.05, llm_noise=0.80, bias_type="constant",
    ))
    S.append(make_scenario(
        "interact.large+sparse+hetero+diff", "interaction",
        n=250, n2=400, n3=300, label_frac=0.03, llm_noise=0.02, llm_noise2=0.50, llm_noise3=0.90,
        bias_type="differential",
    ))
    S.append(make_scenario(
        "interact.mid+extreme-hetero+none", "interaction",
        n=100, n2=150, n3=60, label_frac=0.08, llm_noise=0.01, llm_noise2=0.90, llm_noise3=0.40,
        bias_type="none",
    ))

    # Cross bias MAGNITUDE with every OTHER one-factor-at-a-time dimension
    # above that uses bias_type="differential" at the fixed baseline
    # bias_delta=0.30 (sample_size, balance, label_frac, label_mechanism,
    # llm_noise, heteroskedastic, noise_family, stress, interaction, and
    # shape). Without this, only the dedicated bias_type/bias_magnitude/
    # group_calibration groups show any bias severity below "fully
    # saturated," so the aggregate Type-I calibration plot's uncorrected
    # dots cluster almost entirely at ~alpha or ~1.0 (most of the catalog
    # is one of these ~36 scenarios). Adds two smaller-bias companion
    # scenarios per eligible base scenario -- keeping the original
    # UNCHANGED (same name, same "severe" bias_delta=0.30) so existing
    # results/names stay valid -- rather than replacing it, using the SAME
    # eval-type-relative fractions (3%/7% of range) validated in the
    # standalone bias_magnitude sweep. The eval_type group itself is
    # excluded: it's already exactly this cross (eval_type x bias
    # magnitude) via the dedicated bias_magnitude group above, so adding
    # companions here would just be exact duplicates.
    _EXCLUDED_TAGS = {"eval_type", "bias_type", "bias_magnitude", "group_calibration"}
    extra: list[JudgeBiasSource] = []
    for sc in S:
        if sc.bias_type != "differential" or sc.tag in _EXCLUDED_TAGS:
            continue
        for suffix, frac in [("mildbias", 0.03), ("modbias", 0.07)]:
            extra.append(replace(
                sc, name=f"{sc.name}.{suffix}", bias_delta=_jb_bias_magnitude(sc.eval_type, frac),
            ))
    S.extend(extra)

    return S


# Baseline settings shared by build_ppi_power_sources and
# build_ppi_comparison_label_frac_sources -- the SAME per-eval-type judge-bias
# severity build_judge_bias_sources' "eval_type.*" baseline uses (bias_delta=
# _jb_bias_magnitude(eval_type), n=100, icc=0.20), so the power/comparison
# checks below answer "under the exact bias severity that inflates Type-I
# error in the calibration sweep, does a real effect still get detected" --
# not some easier, less-biased strawman setting.
_PPI_POWER_EVAL_TYPES = ("continuous", "likert", "grades")
# Binary excluded: JudgeBiasSource.effect_size is an additive shift applied
# directly to a 0/1 truth draw (generate_judge_bias_cell's `truth_b2 =
# _marginal(n2) + es`), which only stays valid at es=0 -- see
# _jb_effect_magnitude's docstring.
PPI_POWER_EFFECT_FRACS = (0.0, 0.05, 0.10, 0.15, 0.20, 0.30, 0.40)
"""Effect-size grid for build_ppi_power_sources/build_ppi_comparison_*, as a
fraction of each eval type's own scale span (same convention as
_jb_bias_magnitude's bias_delta fractions). 0.0 is kept as a Type-I
cross-check against build_judge_bias_sources' "eval_type.*" scenarios (same
settings, same expected ~alpha rejection rate) rather than dropped, since it
anchors the left edge of the power curve at the correct floor. 7 points
(vs. the original 4: 0/0.10/0.20/0.40) to resolve the power curve's shape
well enough to read visually -- the original grid's biggest gaps (0.20-0.40)
spanned exactly the region where save_ppi_power_direction_plot's
"cancellation dip" (opposing bias) or crossover (reinforcing bias) happens,
so a coarse grid could make a smooth, well-understood phenomenon look like
a kink or an artifact."""
PPI_COMPARISON_LABEL_FRACS = (0.15, 0.20, 0.30, 0.40)
"""Label-fraction grid for build_ppi_comparison_label_frac_sources, at
_ppi_power_baseline's fixed n=100. Deliberately NOT build_judge_bias_sources'
"lab.*" grid (0.05/0.10/0.20/0.40): _JB_MIN_LAB=15 floors n_lab at 15
regardless of label_frac, and at n=100 both 0.05 (round(5)) and 0.10
(round(10)) floor to the SAME n_lab=15 -- the "lab.*" grid exists to check
Type-I control at each NOMINAL fraction (where the floor collision doesn't
matter, since every one of those scenarios is checked independently), but
here the fractions are plotted against each other on one shared x-axis, so
two of them silently mapping to an identical (n=100, n_lab=15) data-
generating condition would be misleading. This grid's four fractions all
resolve to distinct actual n_lab (15/20/30/40) at n=100 -- see
PPIComparisonResult.n_lab, which reports the REALIZED count rather than
the nominal fraction for exactly this reason."""
PPI_COMPARISON_MODERATE_EFFECT_FRAC = 0.20


def _ppi_power_baseline(eval_type: str) -> dict:
    return dict(
        eval_type=eval_type, icc=0.20, n=100, label_frac=0.20,
        llm_noise=0.20, bias_type="differential", bias_delta=_jb_bias_magnitude(eval_type),
    )


def build_ppi_power_sources() -> list[JudgeBiasSource]:
    """Effect-size sweep, one grid per non-binary eval type, at the SAME
    judge-bias severity build_judge_bias_sources' "eval_type.*" baseline
    uses. build_judge_bias_sources' entire catalog checks Type-I error
    (effect_size=0.0 everywhere -- generate_judge_bias_cell's `es` parameter
    is simply never set above 0 there); this is the complementary check that
    was previously missing entirely: does PPI correction retain the power to
    detect a REAL difference under that same bias, or does it just make
    every test conservative everywhere (which would trivially "fix" Type-I
    at the cost of never rejecting anything)? Tag "power" groups these in
    run()'s reporting/plotting, parallel to build_judge_bias_sources'
    tag-grouped scenarios."""
    return [
        JudgeBiasSource(
            name=f"power.{et}.es={frac:.2f}", tag="power", effect_size=_jb_effect_magnitude(et, frac),
            **_ppi_power_baseline(et),
        )
        for et in _PPI_POWER_EVAL_TYPES
        for frac in PPI_POWER_EFFECT_FRACS
    ]


def build_ppi_power_reinforcing_sources() -> list[JudgeBiasSource]:
    """Same effect_size x eval_type grid as build_ppi_power_sources, but with
    bias_delta's SIGN FLIPPED so the fixed judge bias pushes the SAME
    direction as the injected real effect, instead of the opposite
    direction. build_ppi_power_sources (bias_type="differential") always
    biases group A/x upward (see _jb_biases) while the real effect is always
    injected onto group B/y (`truth_b2 = _marginal(n2) + es`); the observed
    uncorrected difference is therefore approximately `effect_size -
    bias_delta`, which shrinks toward 0 (then grows again) as effect_size
    crosses bias_delta -- the "cancellation dip" visible in the uncorrected
    power curve. Negating bias_delta instead makes the observed uncorrected
    difference `effect_size + bias_delta`: bias and effect stack instead of
    fighting, so the uncorrected line climbs even faster than the corrected
    one, with no dip -- the more dangerous case in practice, since nothing
    about the SHAPE of an inflated-but-monotonic power curve would flag it
    as wrong the way a dip does. Tag "power_reinforcing"; see
    cases/pvalues.py's save_ppi_power_direction_plot, which puts this side
    by side with build_ppi_power_sources' "opposing" direction."""
    def _kwargs(et: str) -> dict:
        kw = _ppi_power_baseline(et)
        kw["bias_delta"] = -_jb_bias_magnitude(et)
        return kw

    return [
        JudgeBiasSource(
            name=f"powerrf.{et}.es={frac:.2f}", tag="power_reinforcing", effect_size=_jb_effect_magnitude(et, frac),
            **_kwargs(et),
        )
        for et in _PPI_POWER_EVAL_TYPES
        for frac in PPI_POWER_EFFECT_FRACS
    ]


def build_ppi_power_nobias_sources() -> list[JudgeBiasSource]:
    """Same effect_size x eval_type grid as build_ppi_power_sources, but with
    bias_type="none" instead of "differential" -- the "no free lunch" check:
    when there's genuinely no judge bias to correct for (the uncorrected
    test is already valid), does PPI correction cost any power relative to
    it? Some cost is expected in principle -- the PPI rectifier adds its own
    bootstrap variance on top of the unlabeled-data estimate -- the question
    this answers is how much. Tag "power_nobias"."""
    def _kwargs(et: str) -> dict:
        kw = _ppi_power_baseline(et)
        kw["bias_type"] = "none"
        return kw

    return [
        JudgeBiasSource(
            name=f"powernb.{et}.es={frac:.2f}", tag="power_nobias", effect_size=_jb_effect_magnitude(et, frac),
            **_kwargs(et),
        )
        for et in _PPI_POWER_EVAL_TYPES
        for frac in PPI_POWER_EFFECT_FRACS
    ]


def build_ppi_comparison_label_frac_sources() -> list[JudgeBiasSource]:
    """Label-fraction sweep, one grid per non-binary eval type, at a fixed
    MODERATE real effect size (PPI_COMPARISON_MODERATE_EFFECT_FRAC) and the
    same baseline bias severity as build_ppi_power_sources. Paired with
    build_ppi_power_sources' effect_size grid (tag "power", reused as-is for
    the comparison sweep's "vs effect size" axis) by
    cases/pvalues.py's PPI estimator-comparison check: for a single
    representative paired-mean estimand (paired_t), how do 5 ways of turning
    (sparse human labels + biased LLM judge scores) into a test compare on
    power -- all-human (oracle), human-labeled-subset-only, LLM-judge-only
    (uncorrected), LLM-judge-with-labeled-items-overwritten-by-truth
    (a naive missing-data-imputation baseline with NO PPI rectifier), and
    PPI-corrected? This grid holds effect_size fixed and varies label_frac
    instead, to show how each arm's power moves as the labeling BUDGET
    changes -- the "how many human labels do you actually need" question
    build_ppi_power_sources' fixed-label_frac=0.20 grid can't answer on its
    own. Tag "compare_label_frac"."""
    def _kwargs(et: str, frac: float) -> dict:
        kw = _ppi_power_baseline(et)
        kw["label_frac"] = frac
        return kw

    return [
        JudgeBiasSource(
            name=f"complab.{et}.lab={frac:.2f}", tag="compare_label_frac",
            effect_size=_jb_effect_magnitude(et, PPI_COMPARISON_MODERATE_EFFECT_FRAC),
            **_kwargs(et, frac),
        )
        for et in _PPI_POWER_EVAL_TYPES
        for frac in PPI_COMPARISON_LABEL_FRACS
    ]


PPI_NLAB_GRID_N_VALUES = (30, 60, 100, 200, 400)
"""Total-item (N) grid for build_ppi_nlab_grid_sources -- same anchor points
as build_judge_bias_sources' "sample_size" tag (60/100/200/400), plus n=30
to extend the small-N end (where PPI's rectifier-variance term is most
likely to matter -- see build_ppi_comparison_label_frac_sources' README
caveat about human_subset occasionally beating ppi at very small n_lab)."""
PPI_NLAB_GRID_NLAB_VALUES = (15, 20, 30, 50, 80)
"""Absolute labeled-item-count (N_lab) grid for build_ppi_nlab_grid_sources
-- starts at _JB_MIN_LAB (15, the floor every n_lab config is subject to
anyway) so every value in this grid is achievable exactly (see
build_ppi_nlab_grid_sources' docstring for how label_frac is back-solved
per cell to hit these counts precisely, independent of N)."""
_PPI_NLAB_GRID_EVAL_TYPES = ("continuous", "likert")


def build_ppi_nlab_grid_sources(effect_frac: float = 0.0) -> list[JudgeBiasSource]:
    """N (total items) x N_lab (ABSOLUTE labeled-item count) grid, crossed
    independently -- unlike build_ppi_comparison_label_frac_sources (which
    only varies label_frac at a fixed N=100, coupling N and N_lab together),
    this answers "does calibration/power depend on the RATIO N_lab/N, or on
    the ABSOLUTE count N_lab" by letting either move while the other holds
    still. label_frac is back-solved to `n_lab / n` per cell so that
    `_jb_labels_independent`/`_jb_labels_shared`'s `n_lab = min(n, max(
    _JB_MIN_LAB, round(n * label_frac)))` reduces to exactly the requested
    n_lab (every value in PPI_NLAB_GRID_NLAB_VALUES is already >= the
    _JB_MIN_LAB floor, so the floor never binds here). Cells where n_lab > n
    are infeasible and skipped.

    Two eval types (continuous, likert) -- NOT the same scoping as
    build_ppi_comparison_label_frac_sources (that function already sweeps
    all three non-binary eval types; an earlier version of this docstring
    claimed otherwise, which was a documentation error, not a considered
    precedent). Likert is included because it's arguably the single most
    common real-world LLM-as-judge output format, so a headline
    calibration/power check silently skipping it was a real gap. Grades is
    deliberately excluded: it's just continuous rescaled to a [0, 100]
    span, so sweeping it here on top of continuous would be redundant, not
    additional coverage. A 5x5 N x N_lab grid times 2 eval types roughly
    doubles this check's compute relative to continuous-only, which is
    accepted here as the cost of covering the dominant real-world format.

    ``effect_frac=0.0`` (the default) is the CALIBRATION question: is the
    PPI-corrected Type-I error still ~alpha across the whole (N, N_lab)
    plane, or does it break down in some region? Pass a nonzero
    ``effect_frac`` (e.g. PPI_COMPARISON_MODERATE_EFFECT_FRAC) for the
    POWER-side companion grid at the same (N, N_lab) cells. Tag
    "nlab_grid" (calibration) or "nlab_grid_power" (power). Scenario names
    are "nlab.<eval_type>.n=<n>.nlab=<n_lab>", the same "<prefix>.
    <eval_type>.<field>=<value>" shape build_ppi_power_sources uses."""
    tag = "nlab_grid" if effect_frac <= 0.0 else "nlab_grid_power"
    sources = []
    for et in _PPI_NLAB_GRID_EVAL_TYPES:
        for n in PPI_NLAB_GRID_N_VALUES:
            for n_lab in PPI_NLAB_GRID_NLAB_VALUES:
                if n_lab > n:
                    continue
                kw = _ppi_power_baseline(et)
                kw["n"] = n
                kw["label_frac"] = n_lab / n
                sources.append(JudgeBiasSource(
                    name=f"nlab.{et}.n={n}.nlab={n_lab}", tag=tag,
                    effect_size=_jb_effect_magnitude(et, effect_frac), **kw,
                ))
    return sources


PPI_FACTORIAL_BIAS_MAGNITUDES: dict[str, float] = {"none": 0.0, "moderate": 0.07, "severe": 0.30}
"""bias_delta fractions -- "moderate"/"severe" match build_judge_bias_sources'
biasmag.*.moderate/biasmag.*.severe labels exactly, so factorial results are
comparable to the existing OFAT bias_magnitude sweep."""
PPI_FACTORIAL_N_VALUES = (60, 200, 400)
PPI_FACTORIAL_NLAB_VALUES = (15, 30, 80)
PPI_FACTORIAL_LABEL_MECHANISMS: dict[str, dict] = {
    "mcar": dict(label_mnar=False, mnar_strength=0.0, mnar_mode="high"),
    "mnar_mild": dict(label_mnar=True, mnar_strength=0.8, mnar_mode="high"),
    "mnar_strong": dict(label_mnar=True, mnar_strength=1.6, mnar_mode="high"),
}
PPI_FACTORIAL_EFFECT_FRACS: dict[str, float] = {"null": 0.0, "moderate": 0.20, "large": 0.40}
PPI_FACTORIAL_BIAS_DIRECTIONS = ("opposing", "reinforcing")
_PPI_FACTORIAL_EVAL_TYPES = ("continuous", "likert")


def build_ppi_factorial_sources() -> list[JudgeBiasSource]:
    """Full factorial cross of the six factors most likely to compound in
    ways this harness's one-factor-at-a-time sweeps (build_judge_bias_sources,
    and this session's effect_size/bias_direction/N_lab additions -- each
    checked one axis at a time against a fixed baseline) can't reveal:
    bias_magnitude x N x N_lab x label_mechanism x effect_size x
    bias_direction, now ALSO crossed with eval_type (continuous, likert).
    Two eval types, not the same scoping build_ppi_comparison_label_frac_
    sources/build_ppi_nlab_grid_sources use for label_frac/N_lab sweeps (an
    earlier version of this docstring claimed "same scoping" as a
    justification for continuous-only -- that was a documentation error:
    build_ppi_comparison_label_frac_sources already sweeps all three
    non-binary eval types, so there was never a real precedent for
    continuous-only here). Likert is included because it's arguably the
    most common real-world LLM-as-judge output format; grades is
    deliberately excluded as redundant with continuous (grades is just
    continuous rescaled to a [0, 100] span). One representative estimand
    (paired_t). Consumed via _run_ppi_comparison_cell/
    run_ppi_comparison_simulation (unchanged -- this is just a new source
    list, not a new execution path), analyzed via cases/pvalues.py's
    fit_ppi_factorial_model (pooled binomial GLM) and a curated set of 2D
    heatmap slices.

    Two skips, one for infeasibility and one for redundancy:
    - n_lab > n is infeasible (same as build_ppi_nlab_grid_sources).
    - bias_direction="reinforcing" is SKIPPED (not just de-prioritized) when
      bias_magnitude="none" OR effect_size="null": bias_direction only flips
      the SIGN of the fixed judge-bias offset (see
      build_ppi_power_reinforcing_sources), and every test here is
      two-sided, so its rejection rate depends only on the offset's
      MAGNITUDE -- "opposing" and "reinforcing" are exact mirror images
      (statistically equivalent) whenever there's no bias to have a
      direction, or no real effect for that direction to interact with.
      Generating both would waste compute on literally redundant cells
      instead of covering new ground -- ~312 cells per eval type survive
      both skips (down from 432 before the redundancy skip,
      3x3x3x3x3x2 minus n_lab>n infeasibility), ~624 total across both
      eval types.

    Small enough, per eval type/paired_t, for a TRUE full factorial (every
    main effect and interaction directly estimable, no confounding to
    reason about) rather than a fractional design -- made tractable by
    generate_judge_bias_pair_cell's ~7.8x lean-generator speedup over
    generate_judge_bias_cell and the PPI bootstrap's existing vectorized
    fast path (evalstats.ppi.correct); see the harness README's efficiency
    note. Scenario names are "fact.<eval_type>.bm=<bm>.n=<n>.nlab=<n_lab>.
    lm=<lm>.es=<es>.bd=<bd>", the same "<prefix>.<eval_type>.<field>=
    <value>..." shape build_ppi_power_sources/build_ppi_nlab_grid_sources
    use -- see cases/pvalues.py's _PPI_FACTORIAL_NAME_RE/
    _parse_ppi_factorial_name for the corresponding parser."""
    sources: list[JudgeBiasSource] = []
    for et in _PPI_FACTORIAL_EVAL_TYPES:
        for bm_label, bm_frac in PPI_FACTORIAL_BIAS_MAGNITUDES.items():
            for n in PPI_FACTORIAL_N_VALUES:
                for n_lab in PPI_FACTORIAL_NLAB_VALUES:
                    if n_lab > n:
                        continue
                    for lm_label, lm_kw in PPI_FACTORIAL_LABEL_MECHANISMS.items():
                        for es_label, es_frac in PPI_FACTORIAL_EFFECT_FRACS.items():
                            for bd_label in PPI_FACTORIAL_BIAS_DIRECTIONS:
                                if bd_label == "reinforcing" and (bm_label == "none" or es_label == "null"):
                                    continue
                                sign = -1.0 if bd_label == "reinforcing" else 1.0
                                name = (
                                    f"fact.{et}.bm={bm_label}.n={n}.nlab={n_lab}.lm={lm_label}."
                                    f"es={es_label}.bd={bd_label}"
                                )
                                sources.append(JudgeBiasSource(
                                    name=name, tag="factorial", eval_type=et, icc=0.20, n=n,
                                    label_frac=n_lab / n, llm_noise=0.20,
                                    bias_type=("none" if bm_label == "none" else "differential"),
                                    bias_delta=sign * _jb_bias_magnitude(et, bm_frac),
                                    effect_size=_jb_effect_magnitude(et, es_frac),
                                    **lm_kw,
                                ))
    return sources


